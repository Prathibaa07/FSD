SELECT * FROM Worker WHERE SALARY > (SELECT AVG(SALARY) FROM Worker);

SELECT FIRST_NAME, LAST_NAME, SALARY FROM Worker WHERE DEPARTMENT = (
    SELECT DEPARTMENT
    FROM Worker
    WHERE FIRST_NAME = 'Monika'
);

